// What the Windows client adds to its pages (index.html and overlay.html) as window.lpcClient. main.js checks that
// every message comes from the site.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lpcClient', {
  version: (process.argv.find((a) => a.startsWith('--lpc-version=')) || '').slice(14),
  screens: () => ipcRenderer.invoke('screens'),
  captureSources: () => ipcRenderer.invoke('capture-sources'),
  captureSource: (id) => ipcRenderer.invoke('capture-source', String(id)),
  shareAudioMode: () => ipcRenderer.sendSync('share-audio-mode'),
  shareAudioCancel: () => ipcRenderer.send('share-audio-cancel'),
  startFilteredAudio: () => ipcRenderer.invoke('filtered-audio-start'),
  stopFilteredAudio: () => ipcRenderer.send('filtered-audio-stop'),
  useScreen: (id) => ipcRenderer.send('screen', String(id)),
  keys: (keys) => ipcRenderer.invoke('keys', keys),
  windowMode: () => ipcRenderer.invoke('window-mode'),
  compact: (height) => ipcRenderer.send('compact', +height || 0),
  front: () => ipcRenderer.send('front'),
  notify: (title, body, action) => ipcRenderer.send('notify', String(title || ''), String(body || ''), action && typeof action === 'object' ? action : null),
  overlay: (state) => ipcRenderer.send('overlay', state),
  overlayDone: () => ipcRenderer.send('overlay-done'),
  discord: (state) => ipcRenderer.send('discord', state),
  update: () => ipcRenderer.send('update'),
  lcu: (method, path, body) => ipcRenderer.invoke('lcu', method, path, body),
  clip: (data, pic, like) => ipcRenderer.invoke('clip', data, pic, like),
  clipsFolder: () => ipcRenderer.send('clips-folder'),
  clips: () => ipcRenderer.invoke('clips'),
  clipRead: (name) => ipcRenderer.invoke('clip-read', String(name)),
  clipRename: (name, to) => ipcRenderer.invoke('clip-rename', String(name), String(to)),
  media: (kind, name) => { const base = ipcRenderer.sendSync('media-base'); return base && `${base}${kind === 'game' ? 'game' : 'clip'}/${encodeURIComponent(String(name))}`; },
  clipTrash: (name) => ipcRenderer.invoke('clip-trash', String(name)),
  clipDrag: (name) => ipcRenderer.send('clip-drag', String(name)),
  clipsClean: (limit, keep) => ipcRenderer.invoke('clips-clean', +limit || 0, Array.isArray(keep) ? keep.map(String) : []),
  metrics: () => ipcRenderer.invoke('metrics'),
  videoFolder: (what) => ipcRenderer.invoke('video-folder', String(what)),
  gameVideo: (what, name, data) => ipcRenderer.invoke('game-video', String(what), name, data),
  combo: (on) => ipcRenderer.send('combo', !!on),
  record: (on) => ipcRenderer.send('record', !!on),
  withLeague: (on) => ipcRenderer.invoke('with-league', typeof on === 'boolean' ? on : undefined),
  ducking: () => ipcRenderer.invoke('ducking'),
  soundSettings: () => ipcRenderer.send('sound-settings'),
  re4: (what, arg) => ipcRenderer.invoke('re4', String(what), arg == null ? '' : String(arg)),
  recordingsFolder: () => ipcRenderer.send('recordings-folder'),
  control: (name) => ipcRenderer.invoke('control', String(name || '')),
  controlStop: () => ipcRenderer.send('control-stop'),
  controlInput: (m) => ipcRenderer.send('control-input', m),
  point: (m) => ipcRenderer.invoke('point', m),
  on: (name, fn) => { if (['league', 'key', 'press', 'overlay', 'overlay-moved', 'update', 'join', 'filtered-audio-data', 'notification-action', 'control-end', 'control-state', 'diag'].includes(name)) ipcRenderer.on(name, (e, v) => fn(v)); },
});
